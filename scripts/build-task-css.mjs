/** 为插件编译 Multica 工具类；所有选择器限定在任务页及其浮层内。 */
import fs from 'node:fs/promises'
import path from 'node:path'
import postcss from 'postcss'
import tailwind from '@tailwindcss/postcss'
import selectorParser from 'postcss-selector-parser'
const input = path.resolve('src/client/multica/theme.css')
const compiled = await postcss([tailwind()]).process(await fs.readFile(input, 'utf8'), { from: input })
compiled.root.walkRules(rule => {
  for (let parent = rule.parent; parent; parent = parent.parent) {
    if (parent.type === 'rule' || (parent.type === 'atrule' && /keyframes$/.test(parent.name))) return
  }
  rule.selector = selectorParser(selectors => {
    selectors.each(selector => {
      if (selector.toString().includes(':root') || selector.toString().trim() === ':host') {
        selector.walkPseudos(pseudo => { if (pseudo.value === ':root' || pseudo.value === ':host') pseudo.replaceWith(selectorParser.className({ value: 'st-ui' })) })
      } else if (['html','body','.dark'].includes(selector.toString().trim())) {
        selector.replaceWith(selectorParser.selector({nodes:[selectorParser.className({value:'st-ui'}), ...(selector.toString().trim()==='.dark'?[selectorParser.className({value:'dark'})]:[])]}))
      } else {
        selector.prepend(selectorParser.combinator({ value: ' ' }))
        selector.prepend(selectorParser.className({ value: 'st-ui' }))
      }
    })
  }).processSync(rule.selector)
})
// 插件挂在已有宿主中；宿主未分层的 reset 不能覆盖插件的工具类。
compiled.root.walkAtRules('layer', rule => {
  if (rule.nodes) rule.replaceWith(rule.nodes)
  else rule.remove()
})
await fs.writeFile('src/client/multica/generated.css', '/* Generated by scripts/build-task-css.mjs. */\n' + compiled.root.toString())
